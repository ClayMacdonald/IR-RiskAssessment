// Extracts the IRP template (.docx) to Markdown so questions can cite it.
// Usage: node scripts/extract-irp.mjs [input.docx] [output.md]
// Defaults: reference/Incident_Response_Plan_2026_XXXXXXXX.docx -> reference/irp-template.md
//
// No dependencies: reads the zip central directory and inflates word/document.xml with zlib.
// Headings keep their Word style level. Numbering is reconstructed from the template's outline
// (1 to 4 for Heading 1, 1.1 for Heading 2, Appendix A to F for Heading 7) because the XML
// does not store the rendered numbers. Confirm against the .docx (see docs/irp-template-discrepancies.md).
import { readFileSync, writeFileSync } from 'node:fs';
import { inflateRawSync } from 'node:zlib';

const input = process.argv[2] || 'reference/Incident_Response_Plan_2026_XXXXXXXX.docx';
const output = process.argv[3] || 'reference/irp-template.md';

function readZipEntry(buf, name) {
  // End of central directory record: last 22+ bytes, signature 0x06054b50.
  let eocd = buf.length - 22;
  while (eocd >= 0 && buf.readUInt32LE(eocd) !== 0x06054b50) eocd--;
  if (eocd < 0) throw new Error('not a zip file');
  const count = buf.readUInt16LE(eocd + 10);
  let p = buf.readUInt32LE(eocd + 16);
  for (let i = 0; i < count; i++) {
    const method = buf.readUInt16LE(p + 10);
    const size = buf.readUInt32LE(p + 20);
    const nameLen = buf.readUInt16LE(p + 28);
    const extraLen = buf.readUInt16LE(p + 30);
    const commentLen = buf.readUInt16LE(p + 32);
    const local = buf.readUInt32LE(p + 42);
    const entry = buf.toString('utf8', p + 46, p + 46 + nameLen);
    if (entry === name) {
      const start = local + 30 + buf.readUInt16LE(local + 26) + buf.readUInt16LE(local + 28);
      const data = buf.subarray(start, start + size);
      return method === 0 ? data : inflateRawSync(data);
    }
    p += 46 + nameLen + extraLen + commentLen;
  }
  throw new Error(`${name} not found`);
}

const decode = (s) =>
  s.replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&apos;/g, "'").replace(/&amp;/g, '&');

const text = (xml) =>
  decode([...xml.matchAll(/<w:t(?: [^>]*)?>([^<]*)<\/w:t>/g)].map((m) => m[1]).join('')).trim();

function toMarkdown(xml) {
  const body = xml.slice(xml.indexOf('<w:body>'));
  const out = [];
  const n = { h1: 0, h2: 0, h3: 0, app: 0 };
  const re = /<w:tbl>[\s\S]*?<\/w:tbl>|<w:p[ >][\s\S]*?<\/w:p>/g;
  let m;
  while ((m = re.exec(body))) {
    const s = m[0];
    if (s.startsWith('<w:tbl')) {
      const rows = (s.match(/<w:tr[ >][\s\S]*?<\/w:tr>/g) || []).map((r) =>
        (r.match(/<w:tc>[\s\S]*?<\/w:tc>/g) || []).map((c) =>
          (c.match(/<w:p[ >][\s\S]*?<\/w:p>/g) || []).map(text).filter(Boolean).join('<br>').replace(/\|/g, '\\|')
        )
      );
      if (!rows.length) continue;
      const width = Math.max(...rows.map((r) => r.length));
      const pad = (r) => [...r, ...Array(width - r.length).fill('')];
      out.push('', `| ${pad(rows[0]).join(' | ')} |`, `|${' --- |'.repeat(width)}`);
      for (const r of rows.slice(1)) out.push(`| ${pad(r).join(' | ')} |`);
      out.push('');
      continue;
    }
    const t = text(s);
    if (!t) continue;
    const style = (s.match(/<w:pStyle w:val="([^"]+)"/) || [])[1] || '';
    if (style.startsWith('TOC')) continue;
    const listed = /<w:numId w:val="[1-9]\d*"/.test(s);
    const level = Number((s.match(/<w:ilvl w:val="(\d+)"/) || [])[1] || 0);
    if (style === 'Heading1') {
      n.h1++, (n.h2 = 0);
      out.push('', `# ${n.h1}. ${t}`, '');
    } else if (style === 'Heading2') {
      n.h2++, (n.h3 = 0);
      out.push('', `## ${n.h1}.${n.h2} ${t}`, '');
    } else if (style === 'Heading3') {
      n.h3++;
      out.push('', `### ${n.h1}.${n.h2}.${n.h3} ${t}`, '');
    } else if (style === 'Heading7') {
      out.push('', `# Appendix ${String.fromCharCode(65 + n.app++)}: ${t}`, '');
    } else if (style === 'Title') {
      out.push(`**${t}**`, '');
    } else if (listed) {
      out.push(`${'  '.repeat(level)}- ${t}`);
    } else {
      out.push('', t, '');
    }
  }
  return out.join('\n').replace(/\n{3,}/g, '\n\n').trim() + '\n';
}

const xml = readZipEntry(readFileSync(input), 'word/document.xml').toString('utf8');
const md = `<!-- Generated by scripts/extract-irp.mjs from ${input.split(/[\\/]/).pop()}. Do not edit. -->\n\n${toMarkdown(xml)}`;
writeFileSync(output, md);
console.log(`Wrote ${output}`);
