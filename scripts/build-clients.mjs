// Compiles src/content/clients/*.json into functions/_lib/clients.generated.js.
// The overrides are served one client at a time by /api/client and never ship in the browser bundle.
// Runs before every build and unit test run (see package.json).
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';

const DIR = 'src/content/clients';
const OUT = 'functions/_lib/clients.generated.js';
const ID_RE = /^[a-z0-9][a-z0-9-]{1,62}$/;

const clients = {};
if (existsSync(DIR)) {
  for (const file of readdirSync(DIR).filter((f) => f.endsWith('.json')).sort()) {
    const clientId = file.slice(0, -5);
    if (!ID_RE.test(clientId)) throw new Error(`${file}: clientId must be lowercase letters, digits and dashes`);
    clients[clientId] = JSON.parse(readFileSync(`${DIR}/${file}`, 'utf8'));
  }
}

mkdirSync('functions/_lib', { recursive: true });
writeFileSync(
  OUT,
  `// Generated by scripts/build-clients.mjs from ${DIR}/. Do not edit.\nexport default ${JSON.stringify(clients, null, 2)};\n`
);
console.log(`Wrote ${OUT} (${Object.keys(clients).length} client overrides)`);
