// Writes docs/question-review.md: one block per question for content review and sign-off.
// Usage: npm run review:export
//
// Safe to rerun. Each block's "Decision" and "Notes" lines, and the sign-off section at the top,
// are carried over from the existing file by question ID, so edits to the bank do not wipe a review.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const OUT = 'docs/question-review.md';
const bank = JSON.parse(readFileSync('src/content/questions.json', 'utf8'));

// Source status per question, from src/content/sources.md. Default applies to anything not listed.
const DEFAULT_STATUS = 'Rule text: Verified (Release 34-100155, 2026-10-30). IRP text: Verified against template; section numbers [VERIFY] (discrepancies item 8).';
const STATUS = {
  roles_annual_review: 'Best practice: periodic review is SEC guidance in Release 34-100155 section II.A, not a rule requirement (sources item 16).',
  roles_tabletop: 'Best practice: Reg S-P does not require a tabletop (sources item 16).',
  detect_what_counts: 'REWORDED 2026-11-02 for the CSIRT. IRP text: Verified against template.',
  detect_how_fast: 'REWORDED 2026-11-02 for the CSIRT. Rule text: Verified, 248.30(a)(4)(iii).',
  contain_device: 'REWORDED 2026-11-02 for the CSIRT; explanation now also covers Section 3.2 evidence steps. IRP text: Verified against template.',
  contain_carrier_counsel: 'REWORDED 2026-11-02: simplified to calling the carrier first. IRP only: insurance and privilege are not Reg S-P requirements.',
  contain_money_movement: 'REWORDED 2026-11-02: plainer wording. IRP text: Verified against template.',
  notice_no_harm: 'REWORDED 2026-11-02: shorter answer, same rule. Rule text: Verified, 248.30(a)(3)(iii) and (a)(4)(i).',
  vendor_diligence: 'REWORDED 2026-11-02: simpler stem; includes written 72-hour commitments (replaces vendor_72_commitment). Rule text: Verified. SOC 2 help line: Verified in Reg S-P app review 2026-10-29, not re-opened (sources item 14).',
  notice_deadline: 'Rule text: Verified. IRP Section 2.6 matches; Appendix A differs (discrepancies item 4).',
  records_ready: 'Rule text: Verified. IRP Section 4 omits two record categories (discrepancies item 2).',
};

const facts = bank.facts;
const fill = (s) => String(s).replace(/\{\{(\w+)\}\}/g, (_, k) => facts[k] ?? `{{${k}}}`);

function previous() {
  if (!existsSync(OUT)) return { signoff: null, marks: {} };
  const text = readFileSync(OUT, 'utf8');
  const signoff = (text.match(/<!-- signoff -->([\s\S]*?)<!-- \/signoff -->/) || [])[1] || null;
  const marks = {};
  for (const block of text.split(/^### /m).slice(1)) {
    const id = (block.match(/`([a-z0-9_]+)`/) || [])[1];
    if (!id) continue;
    marks[id] = {
      decision: (block.match(/^- \*\*Decision:\*\*.*$/m) || [])[0],
      notes: (block.match(/^- \*\*Notes:\*\*.*$/m) || [])[0],
    };
  }
  return { signoff, marks };
}

const { signoff, marks } = previous();
const sections = Object.fromEntries(bank.sections.map((s) => [s.id, s]));

const lines = [
  '# Question bank review',
  '',
  `Generated by \`npm run review:export\` from \`src/content/questions.json\`. ${bank.questions.length} questions, CSIRT and firm leadership only. Placeholders are shown with the default template facts.`,
  '',
  'Mark each block: replace `[ ]` with `[x]` on one choice and add notes. Rerunning the export keeps your marks.',
  'Held-out questions are drafted in `docs/irp-template-discrepancies.md`.',
  'Knowledge options are shuffled for each person. Check that the correct option is not obviously the longest or most detailed one, which cues the answer.',
  '',
  '## Sign-off',
  '',
  '<!-- signoff -->',
  signoff?.trim() ||
    ['- Reviewed by (role title):', '- Date:', '- Bank approved for launch: [ ] Yes [ ] No', '- Conditions:'].join('\n'),
  '<!-- /signoff -->',
  '',
];

let current = 0;
for (const q of bank.questions) {
  if (q.section !== current) {
    current = q.section;
    const s = sections[current];
    lines.push(`## Section ${s.id}: ${s.name}`, '', `IRP: ${s.irp_sections}. Reg S-P: ${s.regsp_requirement}.`, '');
  }
  const prior = marks[q.id] || {};
  lines.push(`### ${fill(q.title)} (\`${q.id}\`)`, '');
  lines.push(`- **Type:** ${q.type}`, `- **Question:** ${fill(q.question)}`);
  if (q.type === 'knowledge') {
    lines.push('- **Options:**');
    for (const o of q.options) lines.push(`  - ${o.correct ? '**(correct)** ' : ''}${fill(o.label)}`);
    lines.push(`- **Correct answer:** ${fill(q.options.find((o) => o.correct).label)}`);
    lines.push(`- **Explanation:** ${fill(q.explanation)}`);
  } else {
    lines.push('- **Options and points:**');
    for (const o of q.options) lines.push(`  - ${o.points}: ${fill(o.label)}`);
    lines.push(`- **Help text:** ${fill(q.help)}`);
    lines.push(`- **Exam finding:** ${fill(q.exam_finding)}`);
  }
  lines.push(
    `- **irp_ref:** ${q.irp_ref}`,
    `- **regsp_ref:** ${q.regsp_ref}`,
    `- **tie_in:** ${fill(q.tie_in)}`,
    `- **Mapped service:** ${q.mapped_service}`,
    `- **Source status:** ${STATUS[q.id] || DEFAULT_STATUS}`,
    prior.decision || '- **Decision:** [ ] Approve [ ] Edit [ ] Reject',
    prior.notes || '- **Notes:**',
    ''
  );
}

writeFileSync(OUT, lines.join('\n'));
console.log(`Wrote ${OUT} (${bank.questions.length} questions)`);
